/**
 * Checks if a sequence of characters resembles realistic English phonotactics
 * (rejects consonant mashing like 'strxyz', 'dfghjk', 'qwrtpsdf')
 */
function hasVowelOrY(word: string): boolean {
  return /[AEIOUY]/.test(word);
}

function hasExcessiveConsonants(word: string): boolean {
  // Reject 5+ consecutive consonants with no vowel
  return /[BCDFGHJKLMNPQRSTVWXZ]{5,}/.test(word);
}

function hasRepeatedChars(word: string): boolean {
  // Reject 4+ identical characters in a row like 'AAAA', 'ZZZZ'
  return /(.)\1{3,}/.test(word);
}

/**
 * Validates whether a candidate string is an authentic English word.
 */
export function isValidEnglishWord(input: string): boolean {
  if (!input) return false;
  const word = input.trim().toUpperCase();

  // Basic sanity check
  if (word.length < 2 || word.length > 25) return false;
  if (!/^[A-Z]+$/.test(word)) return false;

  // Immediate Set lookup
  if (WORD_SET.has(word)) return true;

  // Reject obvious nonsense consonant soups
  if (!hasVowelOrY(word) || hasExcessiveConsonants(word) || hasRepeatedChars(word)) {
    return false;
  }

  // Morphological prefix/suffix stripping to root check
  const suffixes = [
    'ING', 'ED', 'ES', 'S', 'ER', 'EST', 'LY', 'TION', 'SION',
    'ABLE', 'IBLE', 'NESS', 'MENT', 'FUL', 'LESS', 'ITY', 'IZE', 'IST', 'ISM'
  ];

  for (const suf of suffixes) {
    if (word.endsWith(suf) && word.length > suf.length + 2) {
      const root = word.slice(0, -suf.length);
      if (WORD_SET.has(root) || WORD_SET.has(`${root}E`)) {
        return true;
      }
    }
  }

  const prefixes = ['UN', 'RE', 'IN', 'DIS', 'PRE', 'NON', 'OVER', 'SUB', 'MIS', 'OUT', 'TRI', 'BI', 'AUTO'];
  for (const pre of prefixes) {
    if (word.startsWith(pre) && word.length > pre.length + 2) {
      const root = word.slice(pre.length);
      if (WORD_SET.has(root)) {
        return true;
      }
    }
  }

  return false;
}

