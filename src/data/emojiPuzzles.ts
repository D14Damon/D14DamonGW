export function getRandomEmojiPuzzle(category?: string, excludeIds: string[] = []): EmojiPuzzle {
  let pool = EMOJI_PUZZLES;
  if (category && category !== 'All') {
    pool = pool.filter((p) => p.category.toLowerCase() === category.toLowerCase());
    if (pool.length === 0) pool = EMOJI_PUZZLES;
  }

  const remaining = pool.filter((p) => !excludeIds.includes(p.id));
  const choices = remaining.length > 0 ? remaining : pool;
  return choices[Math.floor(Math.random() * choices.length)];
}
